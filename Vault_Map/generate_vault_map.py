def generate_json_output(state):
    """
    Generates a clean JSON string of the vault data for AI parsing.
    Removes system metadata like 'mtime' to save tokens/space.
    """
    clean_data = []
    for rel_path, entry in state.items():
        data = entry["data"]
        # Add path to the data object for context
        item = {"path": rel_path}
        item.update(data)
        clean_data.append(item)

    # Sort for consistent diffs
    clean_data.sort(key=lambda x: x["path"])

    final_output = {
        "metadata": {
            "generated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "description": "High-level index of the Obsidian Vault.",
            "file_count": len(clean_data),
        },
        "files": clean_data,
    }

    return json.dumps(final_output, indent=2)


