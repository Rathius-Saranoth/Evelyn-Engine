"""\r
generate_vault_map.py -- Incrementally builds the Obsidian Vault index for Evelyn.\r
\r
Walks the entire Obsidian Vault (``ROOT_DIR``) and produces:\r
\r
  vault_map_data.json      -- Machine-readable JSON index used by:\r
                               * ``ingest_gists.py`` to upload gist summaries\r
                                 to the Chroma ``evelyn_gists`` collection.\r
                               * ``context_manager.py`` for vault search\r
                                 (``search_vault_map()``).\r
\r
Key design decisions:\r
  - Incremental: Only files with a changed ``mtime`` are re-processed, keeping\r
    runs fast even on large vaults. State is persisted in ``vault_map_data.json``.\r
  - LLM gists: Each file's gist is generated by the model configured in\r
    ``evelyn_config.py`` (MODEL_NAME) via the local Ollama API.\r
    Falls back to a 500-character text slice on failure.\r
  - Vocabulary bridge: Gists include a Keywords line with conversational\r
    search terms to improve RAG retrieval accuracy.\r
  - Exclusions: Configured via ``EXCLUDE_DIRS`` (attachments, templates, archived\r
    entries, hidden folders).\r
\r
Run directly: ``python generate_vault_map.py``\r
"""

