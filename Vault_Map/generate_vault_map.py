def retry_failed_gists(state):
    """
    Phase 2: retry any entries still marked gist_failed=True with escalating timeouts.

    Attempt order: 450s → 600s → 900s.
    Saves state after each success so progress survives an early exit.
    Returns the number of entries still failed after all retry rounds.
    """
    RETRY_TIMEOUTS = [450, 600, 900]

    failed_paths = [
        (rel_path, os.path.join(ROOT_DIR, rel_path))
        for rel_path, entry in state.items()
        if entry.get("data", {}).get("gist_failed", False)
        and os.path.exists(os.path.join(ROOT_DIR, rel_path))
    ]

    if not failed_paths:
        return 0

    print(f"\n[RETRY] {len(failed_paths)} file(s) need gist retries.")

    still_failed = list(failed_paths)
    for attempt, timeout in enumerate(RETRY_TIMEOUTS, start=1):
        if not still_failed:
            break
        print(f"[RETRY] Round {attempt}/{len(RETRY_TIMEOUTS)} — timeout={timeout}s — {len(still_failed)} remaining")
        next_failed = []
        for rel_path, full_path in still_failed:
            print(f"  Retrying: {rel_path}")
            metadata = extract_metadata(full_path, timeout=timeout)
            if metadata and not metadata.get("gist_failed"):
                new_mtime = os.path.getmtime(full_path)
                state[rel_path]["mtime"] = new_mtime
                state[rel_path]["data"] = metadata
                print(f"  -> [OK] Gist generated at timeout={timeout}s")
                # Checkpoint after each success
                with open(STATE_FILE, "w", encoding="utf-8") as f:
                    json.dump(state, f, indent=2)
            else:
                next_failed.append((rel_path, full_path))
        still_failed = next_failed

    return len(still_failed)


def main():
    """
    Entry point: runs the full incremental vault map generation pipeline.

    Execution order:
      1. Load the existing state from ``vault_map_data.json``.
      2. Retroactively clean any thinking-mode artifacts from cached gists.
      3. Phase 1 — ``scan_vault()``: walk the vault, re-process changed files
         and any entries with ``gist_failed=True``, GC deleted entries.
      4. Save state.
      5. Phase 2 — ``retry_failed_gists()``: retry remaining failures with
         escalating timeouts (450s → 600s → 900s). Saves after each success.
      6. Generate ``Obsidian_Vault_Map.md`` and ``The_Last_Week.md``.
      7. Print a summary showing how many gists still need attention.
    """
    # Load State
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, "r", encoding="utf-8") as f:
                state = json.load(f)
        except Exception:
            state = {}
    else:
        state = {}

    # One-time retroactive gist cleanup (fixes artifacts from thinking-mode runs)
    cleaned_count = 0
    for rel_path, entry in state.items():
        if "data" in entry and "gist" in entry["data"]:
            original = entry["data"]["gist"]
            cleaned = clean_gist(original)
            if cleaned != original:
                entry["data"]["gist"] = cleaned
                cleaned_count += 1
    if cleaned_count:
        print(f"Cleaned {cleaned_count} cached gists with thinking artifacts.")

    # Phase 1: Normal incremental scan
    state = scan_vault(state)

    # Save state after Phase 1
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2)

    # Phase 2: Retry failed gists with escalating timeouts
    still_failing = retry_failed_gists(state)

    # Final save (captures any retry successes not already checkpointed)
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, indent=2)

    # Generate JSON output (machine-readable index for search_vault_map)
    generate_json_output(state)
    print(f"Vault map data saved to: {STATE_FILE}")



    # End-of-run failure summary
    total_failed = sum(
        1 for entry in state.values()
        if entry.get("data", {}).get("gist_failed", False)
    )
    if total_failed:
        print(f"\n[GIST SUMMARY] {total_failed} file(s) still using text-slice fallback after all retries.")
        print("  These will be retried automatically on the next vault map generation.")
        print("  To inspect: search for '\"gist_failed\": true' in vault_map_data.json")
    else:
        print("\n[GIST SUMMARY] All gists generated successfully.")


if __name__ == "__main__":
    main()
